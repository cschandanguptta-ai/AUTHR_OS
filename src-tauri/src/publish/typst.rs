// AUTHR_OS — Typst print engine (Phase 6, Sprint 14).
//
// Always generates the print-ready `.typ` source (title page, chapter
// headings, justified body, styled dialogue). When a `typst` binary is
// available (args.typ_bin, `AUTHR_TYPST_BIN`, or PATH) the PDF is compiled
// too; otherwise the response degrades gracefully with `compiled:false` and
// placement guidance — the .typ remains the source of truth.

use crate::error::AppError;
use crate::publish::{cast_names, exports_path, load_book, slugify, turns, BookData};
use serde_json::{json, Value};
use std::process::Command;

/// #49 publish_typst — print-ready typesetting source (+ optional PDF).
pub fn publish_typst(ctx: &mut crate::ipc::Ctx, a: &Value) -> crate::error::IpcResult {
    let book_id = crate::ipc::args::req_i64(a, "book_id")?;
    let data = load_book(&ctx.conn, book_id)?;
    let cast = cast_names(&ctx.conn);
    let title = data.book["title"].as_str().unwrap_or("Untitled");
    let slug = slugify(title);
    let typ_rel = format!("{slug}.typ");
    let typ_path = exports_path(&ctx.root, &typ_rel)?;
    let source = build_typ(&data, &cast);
    std::fs::write(&typ_path, &source)
        .map_err(|e| AppError::bundle(format!("write typ: {e}")))?;

    // Optional compile: explicit arg → env → PATH.
    let bin = a
        .get("typ_bin")
        .and_then(|v| v.as_str())
        .map(str::to_string)
        .or_else(|| std::env::var("AUTHR_TYPST_BIN").ok())
        .or_else(|| find_on_path("typst"));

    let (compiled, pdf_rel, reason) = match bin {
        None => (
            false,
            None,
            Some(
                "typst binary not found — install typst (https://typst.app) or set \
                 AUTHR_TYPST_BIN; the .typ source has been generated"
                    .to_string(),
            ),
        ),
        Some(bin) => {
            let pdf_path = typ_path.with_extension("pdf");
            let out = Command::new(&bin)
                .arg("compile")
                .arg(&typ_path)
                .arg(&pdf_path)
                .output()
                .map_err(|e| AppError::bundle(format!("spawn typst: {e}")))?;
            if out.status.success() && pdf_path.exists() {
                (true, Some(format!("exports/{}", pdf_path.file_name().unwrap().to_string_lossy())), None)
            } else {
                let stderr = String::from_utf8_lossy(&out.stderr);
                let tail: String = stderr.lines().rev().take(6).collect::<Vec<_>>().into_iter().rev().collect::<Vec<_>>().join("; ");
                return Err(AppError::bundle(format!(
                    "typst compile failed: {tail}"
                )));
            }
        }
    };
    ctx.after_commit()?;

    Ok(json!({
        "typ": format!("exports/{typ_rel}"),
        "pdf": pdf_rel,
        "compiled": compiled,
        "reason": reason,
        "chapters": data.chapters.len(),
        "words": data.chapters.iter()
            .map(|ch| ch.segments.iter()
                .map(|s| s["text_content"].as_str().map(|t| t.split_whitespace().count()).unwrap_or(0))
                .sum::<usize>())
            .sum::<usize>(),
    }))
}

fn find_on_path(name: &str) -> Option<String> {
    let path = std::env::var_os("PATH")?;
    std::env::split_paths(&path)
        .map(|dir| dir.join(name))
        .find(|p| p.is_file())
        .map(|p| p.to_string_lossy().into_owned())
}

/// Typst markup for the whole book (professional novel template).
pub fn build_typ(data: &BookData, cast: &std::collections::HashMap<String, String>) -> String {
    let title = typ_escape(data.book["title"].as_str().unwrap_or("Untitled"));
    let author = typ_escape(data.book["author"].as_str().unwrap_or("Anonymous"));
    let mut out = String::from(
        "// Generated by AUTHR_OS — print-ready novel template.\n\
         #set page(paper: \"a5\", margin: 2cm, numbering: \"1\")\n\
         #set text(font: \"Libertinus Serif\", size: 11pt, lang: \"en\")\n\
         #set par(justify: true, leading: 0.8em)\n\n\
         #align(center)[\n\
         \x20 #text(28pt, weight: \"bold\")[",
    );
    out.push_str(&title);
    out.push_str("]\n  #v(0.5em)\n  #text(14pt)[");
    out.push_str(&author);
    out.push_str("]\n]\n#pagebreak()\n\n");

    for (i, ch) in data.chapters.iter().enumerate() {
        let ch_title = typ_escape(ch.row["title"].as_str().unwrap_or("Chapter"));
        let ch_num = ch.row["chapter_number"].as_i64().unwrap_or(i as i64 + 1);
        out.push_str(&format!("= Chapter {ch_num}: {ch_title}\n\n"));
        for t in turns(ch, cast) {
            let text = typ_escape(t.text);
            match t.kind {
                "DIALOGUE" => out.push_str(&format!(
                    "#text(weight: \"bold\")[{}:] \u{201C}{text}\u{201D}\n\n",
                    typ_escape(&t.speaker)
                )),
                "INTERNAL_MONOLOGUE" => {
                    out.push('_');
                    out.push_str(&text);
                    out.push_str("_\n\n");
                }
                _ => out.push_str(&format!("{text}\n\n")),
            }
        }
    }
    out
}

/// Typst escapes: backslash, `#`, `_`, `*`, `[`, `]`, `$`, `@`, `<`, `>`.
fn typ_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 4);
    for c in s.chars() {
        match c {
            '\\' | '#' | '_' | '*' | '[' | ']' | '$' | '@' | '<' | '>' | '`' => {
                out.push('\\');
                out.push(c);
            }
            _ => out.push(c),
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn typ_source_has_title_page_and_chapters() {
        let data = BookData {
            book: json!({"title": "The *Lighthouse*", "author": "A. #Keeper", "id": 1}),
            chapters: vec![crate::publish::ChapterData {
                row: json!({"title": "Fog & Signals", "chapter_number": 1}),
                segments: vec![
                    json!({"segment_type": "NARRATION", "speaker_id": "NARRATOR", "text_content": "The fog rolled in."}),
                    json!({"segment_type": "DIALOGUE", "speaker_id": "MARA", "text_content": "Keep it burning."}),
                    json!({"segment_type": "INTERNAL_MONOLOGUE", "speaker_id": "NARRATOR", "text_content": "Why did I stay?"}),
                ],
            }],
        };
        let cast = [("MARA".to_string(), "Mara".to_string())].into_iter().collect();
        let src = build_typ(&data, &cast);
        assert!(src.contains("The \\*Lighthouse\\*"));
        assert!(src.contains("A. \\#Keeper"));
        assert!(src.contains("= Chapter 1: Fog & Signals"));
        assert!(src.contains("Mara:]"));
        assert!(src.contains("The fog rolled in.\n\n")); // narration: plain
        assert!(src.contains("_Why did I stay?_")); // monologue: italic
    }
}
